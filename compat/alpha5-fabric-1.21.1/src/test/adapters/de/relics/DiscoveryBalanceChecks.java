package de.relics;

import com.google.gson.*;
import de.relics.distribution.*;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.minecraft.server.level.ServerLevel;
import java.lang.reflect.Field;
import java.nio.file.*;
import java.util.*;
import java.util.concurrent.*;
import static de.relics.distribution.DistributionPlanner.*;

/** Diagnostic-only: real generator validation on the production serial actor, no /place. */
public final class DiscoveryBalanceChecks implements ModInitializer {
    private static final Gson JSON=new GsonBuilder().setPrettyPrinting().create();
    private static Object field(Object target,String name)throws Exception {
        Field f=target.getClass().getDeclaredField(name);f.setAccessible(true);return f.get(target);
    }
    @Override public void onInitialize() {
        ServerLifecycleEvents.SERVER_STARTED.register(server->{
            try {
                DistributionRuntime runtime=DistributionRuntime.get(server.overworld());
                if(runtime==null)throw new AssertionError("Missing production runtime");
                var actor=(ScheduledExecutorService)field(runtime,"actor");
                @SuppressWarnings("unchecked") var ready=(CompletableFuture<Void>)field(runtime,"ready");
                ready.thenRun(()->actor.execute(()->{
                    try {run(server.overworld(),runtime);}
                    catch(Throwable error) {
                        try {Files.writeString(Path.of("balance-failure.txt"),error.toString());}catch(Exception ignored) { }
                        error.printStackTrace();
                    }
                }));
            }catch(Exception error){throw new IllegalStateException(error);}
        });
    }
    private static void progress(String value)throws Exception {
        Files.writeString(Path.of("balance-progress.txt"),value+"\n");
        System.out.println("BALANCE "+value);
    }
    private static Site unique(ServerLevel level,TerrainValidator validator,DistributionSettings settings,int x,int z)throws Exception {
        int lower=settings.colossusMinDistance(),upper=lower*2;
        for(int ring=0;ring<8;ring++) {
            if(Thread.currentThread().isInterrupted())throw new CancellationException("Diagnostic stopped");
            for(Candidate c:ColossusSearch.annulus(level.getSeed(),x,z,lower,upper,-29999984,-29999984,29999984,29999984,settings.generationRevision())) {
                Site site=validator.validate(c,Family.COLOSSUS);
                if(site!=null && Math.hypot(site.x()-x,site.z()-z)>=settings.colossusMinDistance())return site;
            }
            lower=upper;upper+=settings.generationRevision()==1 && settings.colossusMinDistance()==30000?20000:settings.colossusMinDistance();
            progress("Colossus search "+settings.cellSize()+" next ring "+lower+".."+upper);
        }
        throw new AssertionError("Bounded diagnostic Colossus search exhausted");
    }
    private static void run(ServerLevel level,DistributionRuntime runtime)throws Exception {
        var journal=(DistributionJournal)field(runtime,"journal");var frozen=journal.state;
        int x=frozen.spawnX,z=frozen.spawnZ,half=Integer.getInteger("relics.balanceHalfWindow",12000);
        var old=new DistributionSettings(2000,800,6000,2400,DistributionSettings.OUTSIDE,DistributionSettings.INSIDE,BiomeRules.STANDARD,8000);
        Map<String,DistributionSettings> cases=new LinkedHashMap<>();
        cases.put("released-discoveries",old);cases.put("expedition",DistributionSettings.EXPEDITION);
        cases.put("balanced",DistributionSettings.BALANCED);cases.put("discoveries",DistributionSettings.DISCOVERY);
        Map<String,Object> report=new LinkedHashMap<>();report.put("seed",level.getSeed());report.put("spawn",List.of(x,z));
        report.put("window",List.of(x-half,z-half,x+half,z+half));report.put("scope","Production planners and native generator; accepted sites, not ticket counts. No chunks generated by this audit.");
        Map<String,Object> results=new LinkedHashMap<>();report.put("cases",results);
        TerrainValidator legacy=new TerrainValidator(level,-29999984,-29999984,29999984,29999984,frozen.interiors,BiomeRules.STANDARD,1);
        TerrainValidator current=new TerrainValidator(level,-29999984,-29999984,29999984,29999984,frozen.interiors,BiomeRules.LANDSCAPES,2);
        TerrainValidator slopeBaseline=new TerrainValidator(level,-29999984,-29999984,29999984,29999984,frozen.interiors,BiomeRules.LANDSCAPES,1);
        for(var entry:cases.entrySet()) {
            long start=System.nanoTime();String name=entry.getKey();var settings=entry.getValue();
            var validator=settings.generationRevision()==1?legacy:current;
            progress(name+" resolving Colossus");
            Site colossus=unique(level,validator,settings,x,z);
            if(name.equals("discoveries") && !colossus.equals(frozen.unique))throw new AssertionError("Diagnostic and production Colossus differ");
            var planner=new DistributionPlanner(settings.policy(),settings,level.getSeed(),frozen.enabled,validator,()->colossus,()->false,frozen.bootstrapX,frozen.bootstrapZ,128);
            List<Site> sites=new ArrayList<>(),slopeSites=new ArrayList<>(),expandedSites=new ArrayList<>();Map<String,Integer> counts=new TreeMap<>();int visited=0;
            int firstX=Math.floorDiv(x-half,settings.cellSize()),lastX=Math.floorDiv(x+half-1,settings.cellSize());
            int firstZ=Math.floorDiv(z-half,settings.cellSize()),lastZ=Math.floorDiv(z+half-1,settings.cellSize());
            int total=(lastX-firstX+1)*(lastZ-firstZ+1);
            for(int cx=firstX;cx<=lastX;cx++)for(int cz=firstZ;cz<=lastZ;cz++) {
                if(Thread.currentThread().isInterrupted())throw new CancellationException("Diagnostic stopped");
                Site site=planner.plan(new Cell(cx,cz));visited++;
                if(site!=null && site.x()>=x-half && site.x()<x+half && site.z()>=z-half && site.z()<z+half) {
                    sites.add(site);String family=site.asset().startsWith("titan_skull_") && !site.asset().equals("titan_skull_2")?"titan_skull":site.asset();
                    counts.merge(family,1,Integer::sum);
                    if(settings.generationRevision()==2 && family.equals("titan_skull_2") && slopeBaseline.validate(site.candidate(),Family.SKULL_2)==null)slopeSites.add(site);
                    if(settings.generationRevision()==2 && family.equals("titan_skull") && legacy.validate(site.candidate(),Family.SKULL)==null)expandedSites.add(site);
                }
                if(visited%16==0)progress(name+" cells "+visited+"/"+total+" accepted "+sites.size());
            }
            Map<String,Object> result=new LinkedHashMap<>();result.put("settings",settings);result.put("accepted",sites.size());result.put("families",counts);result.put("sites",sites);
            result.put("slope_only_sites",slopeSites);result.put("expanded_crown_sites",expandedSites);
            result.put("colossus",colossus);result.put("colossus_distance",Math.hypot(colossus.x()-x,colossus.z()-z));
            result.put("nearest_skull_in_window",sites.stream().filter(s->s.asset().startsWith("titan_skull")).mapToDouble(s->Math.hypot(s.x()-x,s.z()-z)).min().orElse(-1));
            result.put("seconds",(System.nanoTime()-start)/1e9);results.put(name,result);
            Files.writeString(Path.of("balance-audit.json"),JSON.toJson(report));progress(name+" complete "+counts);
        }
        report.put("complete",true);Files.writeString(Path.of("balance-audit.json"),JSON.toJson(report));
        progress("COMPLETE");
    }
}
